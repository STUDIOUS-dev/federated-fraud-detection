"""Aggregates results/study_e/runs.jsonl into results/study_e/aggregate.json and docs/PHASE_E_RESULTS.md."""
import json
from pathlib import Path

from src.config import load_config
from src.experiments.study_report import BANKS, LABEL, _fmt, _table, aggregate, paired
from src.federated.privacy_robustness import zcdp_epsilon

_DEFAULT_ROUNDS = load_config().rounds
AGG_COLS = [("FedAvg", "fedavg"), ("FedMedian", "fedmedian"), ("FedTrimmedAvg", "fedtrimmedavg"), ("Krum", "krum")]


def comparisons():
    c = [
        ("Federation vs isolation", "fedavg", "local"),
        ("Federation vs pooling data", "fedavg", "central"),
        ("1 round vs 5 rounds", "fedavg_rounds1", "fedavg"),
        ("10 rounds vs 5 rounds", "fedavg_rounds10", "fedavg"),
        ("Clip 0.25 vs no clip", "fedavg_clip0.25", "fedavg"),
        ("Clip 0.5 vs no clip", "fedavg_clip0.5", "fedavg"),
        ("Clip 1.0 vs no clip", "fedavg_clip1.0", "fedavg"),
    ]
    for z in ("0.5", "1.0", "2.0", "4.0"):
        c.append((f"DP z={z} vs clip 0.5 (cost of noise)", f"dp_z{z}", "fedavg_clip0.5"))
    c.append(("DP z=1.0 vs local-only", "dp_z1.0", "local"))
    c.append(("DP z=1.0, 10 rounds vs 5 rounds", "dp_z1.0_rounds10", "dp_z1.0"))
    c.append(("Scale attack: clip 0.5 vs plain FedAvg", "attack_scale_x1_fedavg_clip", "attack_scale_x1_fedavg"))
    c.append(("Scale attack + clip vs clean FedAvg", "attack_scale_x1_fedavg_clip", "fedavg"))
    for name in ("alie", "alie_z3", "alie_z5", "minmax"):
        for k in ("x1", "x2"):
            for _, a in AGG_COLS:
                c.append((f"{name} {k} vs clean, {a}", f"adaptive_{name}_{k}_{a}", "fedavg"))
    for _, a in AGG_COLS[:2] + AGG_COLS[3:]:
        c.append((f"alie_z3 x2, {a}: clip 0.5 vs no clip", f"adaptive_alie_z3_x2_{a}_clip",
                  f"adaptive_alie_z3_x2_{a}"))
    return c


def _comm(runs, name):
    r = next((r for r in runs if r["scenario"] == name and "communication" in r), None)
    if not r:
        return None
    c = r["communication"]
    return c["upload_bytes"] + c["download_bytes"]


def _raw_data_bytes():
    """Bytes the banks would ship to pool their (feature-engineered, float32) training data, seed 42."""
    try:
        from src.experiments.framework import build_data
        cd, _, _ = build_data(load_config())
        return int(sum(v["train"][0].nbytes + v["train"][1].nbytes for v in cd.values()))
    except Exception:  # pragma: no cover - report still renders without it
        return None


def render(agg, runs):
    L = []
    nseeds = max((len(v["seeds"]) for v in agg.values()), default=0)
    npos = next(iter(agg.values()))["n_test_pos"] if agg else 0

    def row(name, ms=("pr_auc", "roc_auc", "recall_at_fpr1")):
        a = agg.get(name)
        return [f"`{name}`", len(a["seeds"])] + [_fmt(a["global"][m]) for m in ms] if a else None

    def table_for(names, ms=("pr_auc", "roc_auc", "recall_at_fpr1")):
        rows = [r for r in (row(n, ms) for n in names) if r]
        return _table(rows, ["Scenario", "Seeds"] + [LABEL[m] for m in ms]) if rows else "_not run_"

    L.append("# Phase E Results: Communication, Privacy, Adaptive Attacks\n")
    L.append("_Generated by `python -m src.experiments.study_e` (aggregation: `src/experiments/study_e_report.py`). "
             "Do not edit by hand. Interpretation: `docs/FINAL_REPORT.md`, section \"Phase E\"._\n")
    L.append(f"Each cell is **mean ± std over {nseeds} seeds**, scored on the same reference test pool as the v1.1 "
             f"study (about {npos} fraud cases per seed). Baselines are re-run here so all comparisons are paired "
             "within one software environment; they can differ from `docs/STUDY_RESULTS.md` in the third or fourth "
             "decimal because of library versions.\n")

    L.append("## 1. Baselines\n")
    L.append(table_for(["central", "local", "fedavg"]) + "\n")

    L.append("## 2. Communication cost (E1)\n")
    raw = _raw_data_bytes()
    rows = []
    for name, r in [("fedavg_rounds1", 1), ("fedavg_rounds2", 2), ("fedavg_rounds3", 3), ("fedavg", 5),
                    ("fedavg_rounds10", 10)]:
        if name in agg:
            b = _comm(runs, name)
            rows.append([r, "n/a" if b is None else f"{b / 1024:.1f}", _fmt(agg[name]["global"]["pr_auc"]),
                         _fmt(agg[name]["global"]["recall_at_fpr1"])])
    L.append(_table(rows, ["Rounds", "Total traffic (KiB, all banks, up + down)", "PR-AUC", "Recall@FPR<=1%"]) + "\n")
    if raw:
        L.append(f"For scale: pooling the four banks' training features centrally (float32, seed 42) would move "
                 f"**{raw / 1024:.0f} KiB** of customer-level data once. Model updates are {1025} parameters "
                 "(~4 KiB) per client per direction per round, independent of the number of transactions.\n")

    L.append("## 3. Update clipping and client-level differential privacy (E2)\n")
    L.append(table_for(["fedavg", "fedavg_clip1.0", "fedavg_clip0.5", "fedavg_clip0.25"]) + "\n")
    rows = []
    for name in ["dp_z0.5", "dp_z1.0", "dp_z2.0", "dp_z4.0", "dp_z1.0_rounds10"]:
        if name in agg:
            ov = agg[name]["overrides"]
            rounds = ov.get("rounds", _DEFAULT_ROUNDS)
            eps = zcdp_epsilon(ov["dp_noise_multiplier"], rounds, 1e-5)
            rows.append([f"`{name}`", ov["dp_noise_multiplier"], rounds, f"{eps:.1f}",
                         _fmt(agg[name]["global"]["pr_auc"]), _fmt(agg[name]["global"]["recall_at_fpr1"])])
    L.append(_table(rows, ["Scenario", "Noise multiplier z", "Rounds", "ε (δ=1e-5)", "PR-AUC", "Recall@FPR<=1%"]) + "\n")
    L.append("Mechanism: each client update (local − global) is clipped to L2 norm C = 0.5, the server averages "
             "clipped updates with equal weights and adds Gaussian noise with std z·C/m (m = participating banks). "
             "ε is client-level (protects a whole bank's contribution), from zCDP composition over all rounds "
             "with no amplification claimed. With only 4 clients, the noise per coordinate is large relative to the "
             "averaged signal; real deployments use hundreds of clients for this reason.\n")

    L.append("## 4. Clipping as a defence against the v1.1 scaling attacker\n")
    L.append(table_for(["fedavg", "attack_scale_x1_fedavg", "attack_scale_x1_fedavg_clip",
                        "attack_scale_x1_dp_z1.0"]) + "\n")

    L.append("## 5. Adaptive attacks x aggregation (E4, PR-AUC)\n")
    for k in ("x1", "x2"):
        L.append(f"**{'1 attacker (bank_d) of 4' if k == 'x1' else '2 colluding attackers (bank_c, bank_d) of 4'}**\n")
        rows = []
        for name in ("alie", "alie_z3", "alie_z5", "minmax"):
            r, have = [name], False
            for _, a in AGG_COLS:
                e = agg.get(f"adaptive_{name}_{k}_{a}")
                have |= e is not None
                r.append(_fmt(e["global"]["pr_auc"]) if e else "n/a")
            if have:
                rows.append(r)
        L.append(_table(rows, ["Attack"] + [c for c, _ in AGG_COLS]) + "\n")
    rows = []
    for _, a in AGG_COLS[:2] + AGG_COLS[3:]:
        n0, n1 = f"adaptive_alie_z3_x2_{a}", f"adaptive_alie_z3_x2_{a}_clip"
        if n0 in agg and n1 in agg:
            rows.append([a, _fmt(agg[n0]["global"]["pr_auc"]), _fmt(agg[n1]["global"]["pr_auc"])])
    if rows:
        L.append("**ALIE z=3, 2 attackers: effect of clipping updates to C = 0.5 before aggregation**\n")
        L.append(_table(rows, ["Aggregator", "No clipping", "Clip 0.5"]) + "\n")
    L.append("Threat model: the attackers are omniscient and colluding. In each round they see all honest updates "
             "and send one identical crafted update (the standard setting in which ALIE and Min-Max are evaluated). "
             "`alie`: mean − z·std per coordinate (z = 1, 3 or 5; the paper's formula gives z = 0 for 4 clients). "
             "`minmax`: mean + γ·(−std/‖std‖) with the largest γ that keeps the update no farther from any honest "
             "update than the honest updates are from each other.\n")

    L.append("## 6. Paired comparisons (same seed, A minus B)\n")
    rows = []
    for label, a, b in comparisons():
        p = paired(runs, a, b, "pr_auc")
        if p:
            t = "n/a" if p["t"] is None else f"{p['t']:.1f}"
            rows.append([label, f"{p['mean_diff']:+.3f} ± {p['std_diff']:.3f}", f"{p['wins']}/{p['n']}", t])
    L.append(_table(rows, ["Comparison (A vs B)", "PR-AUC diff ± std", "A wins", "t"]) + "\n")
    L.append("`t` = mean diff / standard error across seeds. With 5 seeds |t| > 2.8 is roughly the 5% level.\n")

    L.append("### Per-bank PR-AUC for the privacy settings\n")
    pb = []
    for n in ["local", "fedavg", "fedavg_clip0.5", "dp_z1.0", "dp_z2.0"]:
        if n in agg:
            pb.append([f"`{n}`"] + [_fmt(agg[n]["per_bank"][b]["pr_auc"], 3) for b in BANKS])
    L.append(_table(pb, ["Scenario"] + BANKS) + "\n")
    return "\n".join(L)


def write_report(runs_path: Path, md_path: Path = Path("docs/PHASE_E_RESULTS.md")):
    runs = [json.loads(l) for l in Path(runs_path).read_text().splitlines() if l.strip()]
    agg = aggregate(runs)
    cmp_out = []
    for label, a, b in comparisons():
        for m in ("pr_auc", "recall_at_fpr1"):
            p = paired(runs, a, b, m)
            if p:
                cmp_out.append({"label": label, **p})
    for name, entry in agg.items():
        c = _comm(runs, name)
        if c is not None:
            entry["communication_bytes"] = c
        ov = entry["overrides"]
        if ov.get("dp_noise_multiplier"):
            entry["epsilon"] = zcdp_epsilon(ov["dp_noise_multiplier"], ov.get("rounds", _DEFAULT_ROUNDS), 1e-5)
    Path(runs_path).parent.joinpath("aggregate.json").write_text(
        json.dumps({"scenarios": agg, "comparisons": cmp_out}, indent=2))
    md_path.write_text(render(agg, runs), encoding="utf-8")
    print(f"Wrote {md_path} and aggregate.json ({len(runs)} runs, {len(agg)} scenarios)")
