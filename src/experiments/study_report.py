"""Aggregates results/study/runs.jsonl into results/study/aggregate.json and docs/STUDY_RESULTS.md."""
import json
import math
from collections import defaultdict
from pathlib import Path

import numpy as np

METRICS = ["pr_auc", "roc_auc", "recall_at_fpr1", "f1", "precision", "recall"]
LABEL = {"pr_auc": "PR-AUC", "roc_auc": "ROC-AUC", "recall_at_fpr1": "Recall@FPR<=1%",
         "f1": "F1@0.5", "precision": "Precision@0.5", "recall": "Recall@0.5"}
BANKS = ["bank_a", "bank_b", "bank_c", "bank_d"]


def _stats(vals):
    a = np.array([np.nan if v is None else v for v in vals], dtype=float)
    a = a[~np.isnan(a)]
    if len(a) == 0:
        return {"mean": None, "std": None, "n": 0}
    return {"mean": float(a.mean()), "std": float(a.std(ddof=1)) if len(a) > 1 else 0.0, "n": int(len(a))}


def _fmt(s, nd=3):
    if s is None or s["mean"] is None:
        return "n/a"
    return f"{s['mean']:.{nd}f} ± {s['std']:.{nd}f}"


def aggregate(runs):
    by = defaultdict(list)
    for r in runs:
        by[r["scenario"]].append(r)
    out = {}
    for name, rs in by.items():
        rs = sorted(rs, key=lambda r: r["seed"])
        entry = {"seeds": [r["seed"] for r in rs], "kind": rs[0]["kind"], "overrides": rs[0]["overrides"],
                 "n_test_pos": rs[0]["n_test_pos"], "global": {}, "per_bank": {}}
        for m in METRICS:
            entry["global"][m] = _stats([r["global_final"].get(m) for r in rs])
        for b in BANKS:
            entry["per_bank"][b] = {m: _stats([r["per_bank_final"].get(b, {}).get(m) for r in rs])
                                    for m in ("pr_auc", "recall_at_fpr1")}
        out[name] = entry
    return out


def paired(runs, a, b, metric="pr_auc"):
    """Per-seed difference a - b over seeds present in both scenarios."""
    ga = {r["seed"]: r["global_final"].get(metric) for r in runs if r["scenario"] == a}
    gb = {r["seed"]: r["global_final"].get(metric) for r in runs if r["scenario"] == b}
    diffs = [ga[s] - gb[s] for s in sorted(set(ga) & set(gb))
             if ga[s] is not None and gb[s] is not None and not math.isnan(ga[s]) and not math.isnan(gb[s])]
    if not diffs:
        return None
    d = np.array(diffs)
    sd = float(d.std(ddof=1)) if len(d) > 1 else 0.0
    se = sd / math.sqrt(len(d)) if len(d) > 1 else float("nan")
    return {"a": a, "b": b, "metric": metric, "n": len(d), "mean_diff": float(d.mean()), "std_diff": sd,
            "se": se, "t": float(d.mean() / se) if se and se > 0 else None, "wins": int((d > 0).sum())}


def comparisons():
    c = [
        ("Federation vs isolation", "fedavg", "local"),
        ("Federation vs pooling data", "fedavg", "central"),
        ("Pooling vs isolation", "central", "local"),
        ("FedProx mu=0.01 vs FedAvg", "fedprox_mu0.01", "fedavg"),
        ("FedProx mu=0.1 vs FedAvg", "fedprox_mu0.1", "fedavg"),
        ("FedProx mu=1.0 vs FedAvg", "fedprox_mu1.0", "fedavg"),
        ("IID training data vs non-IID (FedAvg)", "fedavg_iid", "fedavg"),
        ("Fed vs local, IID", "fedavg_iid", "local_iid"),
        ("Fed vs local, unequal sizes", "fedavg_sizes", "local_sizes"),
        ("Fed vs local, imbalance", "fedavg_imbalance", "local_imbalance"),
        ("Dropout 25% vs none", "fedavg_dropout0.25", "fedavg"),
        ("Dropout 50% vs none", "fedavg_dropout0.5", "fedavg"),
    ]
    for a in ("fedmedian", "fedtrimmedavg", "krum"):
        c.append((f"{a} (no attack) vs FedAvg", f"{a}_clean", "fedavg"))
    for attack in ("scale", "signflip", "labelflip"):
        c.append((f"FedAvg under {attack} x1 vs clean FedAvg", f"attack_{attack}_x1_fedavg", "fedavg"))
    return c


def _table(rows, header):
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    lines += ["| " + " | ".join(str(x) for x in r) + " |" for r in rows]
    return "\n".join(lines)


def render(agg, runs):
    L = []
    nseeds = max((len(v["seeds"]) for v in agg.values()), default=0)
    npos = next(iter(agg.values()))["n_test_pos"] if agg else 0
    L.append("# Multi-seed Study Results\n")
    L.append("_Generated by `python -m src.experiments.study` (aggregation: `src/experiments/study_report.py`). "
             "Do not edit by hand._\n")
    L.append(f"Each cell is **mean ± std over {nseeds} seeds** (seed changes the synthetic data, model init and "
             "client training order). Every scenario is scored on the **same reference test pool** of the "
             f"default federation for that seed (about {npos} fraud cases of ~13.6k transactions per seed), so "
             "numbers are comparable across rows. A single seed's PR-AUC moves by several hundredths from noise "
             "alone; read differences against the paired std below, not the raw means.\n")

    def row(name, ms=("pr_auc", "roc_auc", "recall_at_fpr1", "f1")):
        a = agg.get(name)
        return [f"`{name}`", len(a["seeds"])] + [_fmt(a["global"][m]) for m in ms] if a else None

    def table_for(names, ms=("pr_auc", "roc_auc", "recall_at_fpr1", "f1")):
        rows = [r for r in (row(n, ms) for n in names) if r]
        return _table(rows, ["Scenario", "Seeds"] + [LABEL[m] for m in ms]) if rows else "_not run_"

    L.append("## 1. Baselines and federated strategies\n")
    L.append(table_for(["central", "local", "fedavg", "fedprox_mu0.01", "fedprox_mu0.1", "fedprox_mu1.0"]) + "\n")
    L.append("## 2. Data distribution, client size, imbalance, dropout\n")
    L.append(table_for(["central_iid", "local_iid", "fedavg_iid", "local_sizes", "fedavg_sizes", "local_imbalance",
                        "fedavg_imbalance", "fedavg_dropout0.25", "fedavg_dropout0.5"]) + "\n")
    L.append("`*_iid` trains on identical-profile banks; `*_sizes` uses client sizes [200, 50, 1000, 750]; "
             "`*_imbalance` shrinks bank_a to 10 customers. All are scored on the default (non-IID, equal-size) test pool.\n")

    L.append("### Per-bank PR-AUC (mean over seeds; each bank's own held-out transactions)\n")
    pb_rows = []
    for n in ["local", "fedavg", "central", "local_sizes", "fedavg_sizes", "local_imbalance", "fedavg_imbalance"]:
        if n in agg:
            pb_rows.append([f"`{n}`"] + [_fmt(agg[n]["per_bank"][b]["pr_auc"], 3) for b in BANKS])
    L.append(_table(pb_rows, ["Scenario"] + BANKS) + "\n")

    L.append("## 3. Robustness: attack x aggregation (PR-AUC)\n")
    for k in ("x1", "x2"):
        L.append(f"**{'1 attacker (bank_d) of 4' if k == 'x1' else '2 attackers (bank_c, bank_d) of 4'}**\n")
        rows = []
        for attack in ("scale", "signflip", "labelflip"):
            r = [attack]
            have = False
            for a in ("fedavg", "fedmedian", "fedtrimmedavg", "krum"):
                e = agg.get(f"attack_{attack}_{k}_{a}")
                have |= e is not None
                r.append(_fmt(e["global"]["pr_auc"]) if e else "n/a")
            if have:
                rows.append(r)
        L.append(_table(rows, ["Attack", "FedAvg", "FedMedian", "FedTrimmedAvg", "Krum"]) + "\n")
    L.append(f"Reference without any attacker: " + ", ".join(
        f"{a} {_fmt(agg[n]['global']['pr_auc'])}" for a, n in
        [("FedAvg", "fedavg"), ("FedMedian", "fedmedian_clean"), ("FedTrimmedAvg", "fedtrimmedavg_clean"),
         ("Krum", "krum_clean")] if n in agg) + ".\n")
    L.append("Attacks: `scale` = send weights x -10; `signflip` = send global + (-5)(local - global); "
             "`labelflip` = train on inverted fraud labels. FedTrimmedAvg trims 1 of 4 clients per side (beta=0.25); "
             "Krum keeps 1 client.\n")

    L.append("**Caveats.** (1) Krum returns a single client's model (no averaging), so its robustness is bought with "
             "the loss of any federation gain. (2) Krum's guarantee needs n > 2f+2; with n=4, f=2 it is outside its "
             "theory. Here it survives only because the two attackers are non-adaptive and far from every honest "
             "client; two colluding or mimicking attackers would very likely defeat it. (3) Median and trimmed mean "
             "are expected to break at 50% attackers, and they do. (4) `signflip` and `labelflip` barely hurt FedAvg "
             "at these settings (local updates are small: lr=0.001, 2 epochs, 5 rounds), so they are weak attacks, "
             "not evidence of resilience. (5) FedAvg under the `scale` attack is bimodal across seeds "
             "(hence the large std).\n")

    L.append("## 4. Paired comparisons (same seed, A minus B)\n")
    rows = []
    for label, a, b in comparisons():
        for m in ("pr_auc", "recall_at_fpr1"):
            p = paired(runs, a, b, m)
            if p:
                t = "n/a" if p["t"] is None else f"{p['t']:.1f}"
                rows.append([label, LABEL[m], f"{p['mean_diff']:+.3f} ± {p['std_diff']:.3f}", f"{p['wins']}/{p['n']}", t])
    L.append(_table(rows, ["Comparison (A vs B)", "Metric", "Mean diff ± std", "A wins", "t"]) + "\n")
    L.append("`t` = mean diff / standard error across seeds. With 5 seeds |t| > 2.8 is roughly the 5% level; "
             "treat anything smaller as indistinguishable from noise.\n")

    L.append("## 5. Scenarios not yet run\n")
    missing = [n for n in ("fedavg", "local", "central") if n not in agg]
    L.append("None of the core scenarios are missing.\n" if not missing else f"Missing: {missing}\n")
    return "\n".join(L)


def write_report(runs_path: Path, md_path: Path = Path("docs/STUDY_RESULTS.md")):
    runs = [json.loads(l) for l in Path(runs_path).read_text().splitlines() if l.strip()]
    agg = aggregate(runs)
    cmp_out = []
    for label, a, b in comparisons():
        for m in ("pr_auc", "recall_at_fpr1"):
            p = paired(runs, a, b, m)
            if p:
                cmp_out.append({"label": label, **p})
    Path(runs_path).parent.joinpath("aggregate.json").write_text(
        json.dumps({"scenarios": agg, "comparisons": cmp_out}, indent=2))
    md_path.write_text(render(agg, runs), encoding="utf-8")
    print(f"Wrote {md_path} and aggregate.json ({len(runs)} runs, {len(agg)} scenarios)")
