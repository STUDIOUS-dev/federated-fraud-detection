"""Aggregates results/real_data_e/runs.jsonl into results/real_data_e/aggregate.json and
docs/REAL_DATA_PHASE_E_RESULTS.md (numbers only; interpretation lives in docs/FINAL_REPORT.md)."""
import json
from pathlib import Path

from src.experiments.study_report import LABEL, _fmt, _table, aggregate, paired
from src.federated.privacy_robustness import zcdp_epsilon

AGG_COLS = [("FedAvg", "fedavg"), ("FedMedian", "fedmedian"), ("Krum", "krum")]
ATTACKS = [("ALIE z = 1", "alie"), ("ALIE z = 3", "alie_z3"), ("ALIE z = 5", "alie_z5"), ("Min-Max", "minmax")]
_CLEAN = {"fedavg": "fedavg", "fedmedian": "fedmedian_clean", "krum": "krum_clean"}


def _settings():
    from src.experiments.real_data_e import DP_CLIP, ROUNDS
    return DP_CLIP, ROUNDS


def comparisons():
    c = [("Federation vs isolation", "fedavg", "local"),
         ("Federation vs pooling data", "fedavg", "central"),
         ("FedMedian vs FedAvg (no attack)", "fedmedian_clean", "fedavg"),
         ("Krum vs FedAvg (no attack)", "krum_clean", "fedavg"),
         ("Clipping vs no clipping", "fedavg_clip", "fedavg")]
    for z in ("0.5", "1.0", "2.0"):
        c.append((f"DP z={z} vs clipping only (cost of noise)", f"dp_z{z}", "fedavg_clip"))
    c.append(("DP z=1.0 vs local-only", "dp_z1.0", "local"))
    c.append(("Scale attack: clipping vs plain FedAvg", "attack_scale_x1_fedavg_clip", "attack_scale_x1_fedavg"))
    c.append(("Scale attack + clipping vs clean FedAvg", "attack_scale_x1_fedavg_clip", "fedavg"))
    c.append(("Scale attack: FedMedian vs plain FedAvg", "attack_scale_x1_fedmedian", "attack_scale_x1_fedavg"))
    for label, name in ATTACKS:
        for _, a in AGG_COLS:
            c.append((f"{label}, 2 attackers vs clean, {a}", f"adaptive_{name}_x2_{a}", _CLEAN[a]))
    return c


def _row(agg, n, metrics=("pr_auc", "roc_auc", "recall_at_fpr1")):
    e = agg.get(n)
    if e is None:
        return None
    return [f"`{n}`", len(e["seeds"])] + [_fmt(e["global"][m]) for m in metrics]


def _block(agg, names):
    rows = [r for r in (_row(agg, n) for n in names) if r]
    return _table(rows, ["Scenario", "Seeds", LABEL["pr_auc"], LABEL["roc_auc"], LABEL["recall_at_fpr1"]])


def _comm_kib(runs, name):
    r = next((r for r in runs if r["scenario"] == name and "communication" in r), None)
    if not r:
        return None
    return (r["communication"]["upload_bytes"] + r["communication"]["download_bytes"]) / 1024


def render(agg, runs):
    clip, rounds = _settings()
    nseeds = max((len(v["seeds"]) for v in agg.values()), default=0)
    npos = next(iter(agg.values()))["n_test_pos"] if agg else 0
    L = ["# Phase E on real data: OpenML credit-card (E5)\n",
         "_Generated by `python -m src.experiments.real_data_e` (aggregation: `src/experiments/real_data_e_report.py`). "
         "Do not edit by hand. Interpretation: `docs/FINAL_REPORT.md`, section 7.5._\n",
         f"Each cell is **mean ± std over {nseeds} seeds**. Data and banks are those of the frozen real-data study "
         "(`docs/REAL_DATA_RESULTS.md`): temporal split by row order (80/20), training rows assigned at random to "
         "4 banks holding 45 / 30 / 15 / 10% of the rows with an unequal fraud share, features standardised on the "
         f"training split. The test split has only **{npos} frauds**, so differences between healthy methods are "
         f"noisy. {rounds} rounds, 2 local epochs, the same MLP and the same clients and Tracked* strategies as the "
         "synthetic Phase E study. Baselines are re-run here (in-process runner) and can differ slightly from the "
         "frozen real-data study, which used its own aggregation loop.\n",
         "Attackers: the single scaling attacker is bank_a (the largest bank, as in the frozen study) and sends its "
         "weights × −10 (the synthetic study's attack; the frozen real-data study scaled the update by +10 instead). "
         "The two adaptive attackers are bank_c and bank_d (25% of the rows, 2 of 4 clients). FedTrimmedAvg is "
         "omitted: it gave exactly the same numbers as FedMedian in every synthetic Phase E scenario.\n"]

    L.append("## 1. Baselines\n")
    L.append(_block(agg, ["central", "local", "fedavg", "fedmedian_clean", "krum_clean"]) + "\n")
    kib = _comm_kib(runs, "fedavg")
    if kib:
        L.append(f"Communication for FedAvg: **{kib:.1f} KiB** in total over {rounds} rounds for all four banks "
                 "(upload + download). Pooling the training features centrally (float32) would move about "
                 "26 MB once.\n")

    L.append("## 2. Update clipping and client-level differential privacy\n")
    rows = []
    for n, z in [("fedavg", None), ("fedavg_clip", 0.0)] + [(f"dp_z{z}", z) for z in (0.5, 1.0, 2.0)]:
        e = agg.get(n)
        if not e:
            continue
        eps = "∞" if not z else f"{zcdp_epsilon(z, rounds, 1e-5):.1f}"
        rows.append([f"`{n}`", "–" if z is None else clip, "–" if z is None else z, "–" if z is None else eps,
                     _fmt(e["global"]["pr_auc"]), _fmt(e["global"]["recall_at_fpr1"])])
    L.append(_table(rows, ["Scenario", "Clip norm C", "Noise multiplier z", "ε (δ=1e-5)", "PR-AUC",
                           "Recall@FPR<=1%"]) + "\n")
    norms = [v for r in runs if r["scenario"] == "fedavg_clip" for rd in r.get("update_norms", {}).values()
             for v in rd.values()]
    if norms:
        import numpy as np
        L.append(f"Honest update norms received in `fedavg_clip` (before clipping): median {np.median(norms):.2f}, "
                 f"range {min(norms):.2f}–{max(norms):.2f} over all rounds and banks. C = {clip} is about the "
                 "median, so the first rounds are clipped hardest. ε is client-level, from zCDP composition over "
                 "all rounds with no amplification claimed.\n")

    L.append("## 3. Single weight-scaling attacker (bank_a)\n")
    L.append(_block(agg, ["fedavg", "attack_scale_x1_fedavg", "attack_scale_x1_fedavg_clip",
                          "attack_scale_x1_fedmedian"]) + "\n")

    L.append("## 4. Adaptive attacks, 2 colluding attackers of 4 (PR-AUC)\n")
    rows = [["none"] + [_fmt(agg[_CLEAN[a]]["global"]["pr_auc"]) if _CLEAN[a] in agg else "n/a"
                        for _, a in AGG_COLS]]
    for label, name in ATTACKS:
        r = [label] + [_fmt(agg[f"adaptive_{name}_x2_{a}"]["global"]["pr_auc"])
                       if f"adaptive_{name}_x2_{a}" in agg else "n/a" for _, a in AGG_COLS]
        if any(v != "n/a" for v in r[1:]):
            rows.append(r)
    L.append(_table(rows, ["Attack"] + [c for c, _ in AGG_COLS]) + "\n")
    L.append("Threat model as in `docs/PHASE_E_RESULTS.md`: omniscient, colluding attackers that see all honest "
             "updates each round and send one identical crafted update.\n")

    L.append("## 5. Per-seed PR-AUC of the attacked scenarios\n")
    seeds = sorted({r["seed"] for r in runs})
    by = {(r["scenario"], r["seed"]): r["global_final"].get("pr_auc") for r in runs}
    rows = []
    for n in ["fedavg", "attack_scale_x1_fedavg"] + [f"adaptive_{name}_x2_{a}" for _, name in ATTACKS
                                                     for _, a in AGG_COLS]:
        if any((n, s) in by for s in seeds):
            rows.append([f"`{n}`"] + [f"{by[(n, s)]:.3f}" if by.get((n, s)) is not None else "–" for s in seeds])
    L.append(_table(rows, ["Scenario"] + [f"seed {s}" for s in seeds]) + "\n")

    L.append("## 6. Paired comparisons (same seed, A minus B)\n")
    rows = []
    for label, a, b in comparisons():
        p = paired(runs, a, b, "pr_auc")
        if p:
            t = "n/a" if p["t"] is None else f"{p['t']:.1f}"
            rows.append([label, f"{p['mean_diff']:+.3f} ± {p['std_diff']:.3f}", f"{p['wins']}/{p['n']}", t])
    L.append(_table(rows, ["Comparison (A vs B)", "PR-AUC diff ± std", "A wins", "t"]) + "\n")
    L.append("`t` = mean diff / standard error across seeds. With 5 seeds |t| > 2.8 is roughly the 5% level.\n")
    return "\n".join(L)


def write_report(runs_path: Path, md_path: Path = Path("docs/REAL_DATA_PHASE_E_RESULTS.md")):
    runs = [json.loads(l) for l in Path(runs_path).read_text().splitlines() if l.strip()]
    agg = aggregate(runs)
    _, rounds = _settings()
    cmp_out = []
    for label, a, b in comparisons():
        for m in ("pr_auc", "recall_at_fpr1"):
            p = paired(runs, a, b, m)
            if p:
                cmp_out.append({"label": label, **p})
    for name, entry in agg.items():
        z = entry["overrides"].get("dp_noise_multiplier")
        if z:
            entry["epsilon"] = zcdp_epsilon(z, rounds, 1e-5)
    Path(runs_path).parent.joinpath("aggregate.json").write_text(
        json.dumps({"scenarios": agg, "comparisons": cmp_out}, indent=2))
    md_path.write_text(render(agg, runs), encoding="utf-8")
    print(f"Wrote {md_path} and aggregate.json ({len(runs)} runs, {len(agg)} scenarios)")
